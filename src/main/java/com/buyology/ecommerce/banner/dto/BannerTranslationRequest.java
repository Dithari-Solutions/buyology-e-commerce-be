package com.buyology.ecommerce.banner.dto;

public class BannerTranslationRequest {

    private String textAz;
    private String textEn;
    private String textAr;
    private String buttonLabelAz;
    private String buttonLabelEn;
    private String buttonLabelAr;

    public String getTextAz() { return textAz; }
    public void setTextAz(String textAz) { this.textAz = textAz; }
    public String getTextEn() { return textEn; }
    public void setTextEn(String textEn) { this.textEn = textEn; }
    public String getTextAr() { return textAr; }
    public void setTextAr(String textAr) { this.textAr = textAr; }
    public String getButtonLabelAz() { return buttonLabelAz; }
    public void setButtonLabelAz(String buttonLabelAz) { this.buttonLabelAz = buttonLabelAz; }
    public String getButtonLabelEn() { return buttonLabelEn; }
    public void setButtonLabelEn(String buttonLabelEn) { this.buttonLabelEn = buttonLabelEn; }
    public String getButtonLabelAr() { return buttonLabelAr; }
    public void setButtonLabelAr(String buttonLabelAr) { this.buttonLabelAr = buttonLabelAr; }
}
